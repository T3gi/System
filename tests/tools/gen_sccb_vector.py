#!/usr/bin/env python3
"""Turn the SCCB part of a PulseView I2C export into a C test vector.

Reads docs/captures/i2c_init_temp_check_export.txt (PulseView "Export all
annotations" of the i2c decoder, 8 MHz) and writes every OV7670 (0x21)
transaction from the COM7 soft reset to the end of the init burst.

SCCB has no repeated START, so a register read shows up as two transactions:
a 2-phase write of the register number, then a 1-byte read.  Both are kept
as separate entries, exactly as they appeared on the bus.

Usage: gen_sccb_vector.py <export.txt> <out.h>
"""
import re
import sys

SAMPLE_HZ = 8_000_000
CAM = "21"
GAP_END_S = 0.500          # burst is over after 0.5 s of SCCB silence (longest
                           # pause inside it is the 100 ms after the COM7 reset)

line_re = re.compile(r"^(\d+)-(\d+) I²C: Address/data: (.*)$")


def transactions(path):
    cur = None
    for line in open(path, encoding="utf-8"):
        m = line_re.match(line.strip())
        if not m:
            continue
        t0, text = int(m.group(1)), m.group(3)
        if text == "Start":
            cur = {"t": t0, "addr": None, "rw": None, "data": []}
        elif cur is None:
            continue
        elif text.startswith("Address write: "):
            cur["addr"], cur["rw"] = text.split(": ")[1], "W"
        elif text.startswith("Address read: "):
            cur["addr"], cur["rw"] = text.split(": ")[1], "R"
        elif text.startswith("Data write: ") or text.startswith("Data read: "):
            cur["data"].append(int(text.split(": ")[1], 16))
        elif text == "Stop":
            yield cur
            cur = None


def main(src, dst):
    cam = [t for t in transactions(src) if t["addr"] == CAM]
    start = next(i for i, t in enumerate(cam)
                 if t["rw"] == "W" and t["data"][:2] == [0x12, 0x80])
    burst = [cam[start]]
    for t in cam[start + 1:]:
        if (t["t"] - burst[-1]["t"]) / SAMPLE_HZ > GAP_END_S:
            break
        burst.append(t)

    rows = []
    for t in burst:
        ms = t["t"] * 1000.0 / SAMPLE_HZ
        if t["rw"] == "W" and len(t["data"]) == 2:
            rows.append("    { SCCB_W3, 0x%02X, 0x%02X },   /* %9.3f ms */" % (t["data"][0], t["data"][1], ms))
        elif t["rw"] == "W" and len(t["data"]) == 1:
            rows.append("    { SCCB_W2, 0x%02X, 0x00 },   /* %9.3f ms */" % (t["data"][0], ms))
        elif t["rw"] == "R" and len(t["data"]) == 1:
            rows.append("    { SCCB_R,  0x00, 0x%02X },   /* %9.3f ms */" % (t["data"][0], ms))
        else:
            raise SystemExit("unexpected transaction at %.3f ms: %r" % (ms, t))

    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tests/tools/gen_sccb_vector.py from\n")
        f.write(" * docs/captures/i2c_init_temp_check_export.txt — do not edit by hand.\n")
        f.write(" * OV7670 init as seen on the bus: COM7 reset .. end of HREF/VREF window.\n")
        f.write(" * Times are from the start of the capture. */\n")
        f.write("#ifndef OV7670_CIF_INIT_VECTOR_H\n#define OV7670_CIF_INIT_VECTOR_H\n\n")
        f.write('#include "sccb_vector.h"\n\n')
        f.write("static const sccb_vec_t ov7670_cif_init_vector[] = {\n")
        f.write("\n".join(rows))
        f.write("\n};\n\n#endif\n")
    print("%d transactions, %.3f .. %.3f ms" % (
        len(burst), burst[0]["t"] * 1000.0 / SAMPLE_HZ, burst[-1]["t"] * 1000.0 / SAMPLE_HZ))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
